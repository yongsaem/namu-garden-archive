export const 망국을애도하는시인 = {
    name: "망국을 애도하는 시인",
    type: "tunnel",
    effect2pc: "양자 속성 피해 10% 증가",
    effect4pc: "장착한 캐릭터의 속도가 8% 감소한다. 전투 진입 전 장착한 캐릭터의 속도가 110/95 미만이면, 장착한 캐릭터의 치명타 확률이 20%/32% 증가한다. 해당 효과는 동시에 장착한 캐릭터의 기억 정령에게도 적용된다"
};

망국을애도하는시인.set2Buffs = {
    "양자 속성 피해 증가": 10
};
망국을애도하는시인.set4Buffs = {
    "속도": -8
};

망국을애도하는시인.dynamicBuffs = {
    "치명타 확률": (장착캐릭터) => {
        const 속도 = 장착캐릭터.finalStats["속도"];
        return 속도 < 95 ? 32 : 속도 < 110 ? 20 : 0;
    }
};
