export const 사색하는거목 = {
    name: "사색하는 거목",
    type: "accessory",
    effect2pc: "장착한 캐릭터의 속도가 6% 증가한다. 장착한 캐릭터의 속도가 135/180 이상이면, 장착한 캐릭터 및 해당 기억 정령의 총 회복량이 12%/20% 증가한다."
};

사색하는거목.set2Buffs = {
    "속도": 6
};

사색하는거목.dynamicBuffs = {
    "치유량 보너스": (장착캐릭터) => {
        const 속도 = 장착캐릭터.finalStats["속도"];
        return 속도 >= 180 ? 20 : 속도 >= 135 ? 12 : 0;
    }
};
